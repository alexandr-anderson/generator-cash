export const LEGAL_VERSION = "2026-09-11";
export const SUPPORT_EMAIL = "service@postvmeste.ru";

export type LegalSection = { title: string; paragraphs: string[] };

/**
 * Дата редакции человеческим языком. В LEGAL_VERSION лежит ISO — он уходит в
 * ConsentRecord и сравнивается как строка, поэтому формат там не трогаем;
 * читателю договора показываем дату, а не то, что выглядит как номер сборки.
 */
export function legalVersionLabel(version = LEGAL_VERSION) {
  const label = new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(version));
  // Кикер набран капсом, и хвост «Г.» в нём выглядит как обрубок.
  return label.replace(/\s*г\.$/, "");
}

export function parseRegisterConsent(body: unknown) {
  if (!body || typeof body !== "object") return false;
  return (body as { consent?: unknown }).consent === true;
}

